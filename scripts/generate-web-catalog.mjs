import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getCatalog, openDatabase } from '../database.mjs';

const root = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const output = path.join(root, 'data', 'catalog-inline.js');
const database = openDatabase();

try {
  const catalog = getCatalog(database);
  writeFileSync(output, `/* Generated by npm run build:web. */\nwindow.SignBySignCatalog = ${JSON.stringify(catalog)};\n`, 'utf8');
  console.log(`Standalone web catalog: ${output}`);
} finally {
  database.close();
}
